    fn generate_forward_declarations(&self, class_def: &ClassDef) -> Result<String, String> {
        let mut out = String::new();
        let is_builtin = Self::is_builtin_runtime_class(&class_def.name);
        if !is_builtin {
            out.push_str(&format!(
                "{}* {}_new(void);\n",
                class_def.name, class_def.name
            ));

            let has_init = class_def.members.iter().any(|m| match m {
                Member::Method { name, .. } => name == "init",
                _ => false,
            });
            if !has_init {
                out.push_str(&format!(
                    "void {}_init({}* self);\n",
                    class_def.name, class_def.name
                ));
            }
        }

        for m in &class_def.members {
            if let Member::Method {
                name,
                params,
                body,
                return_type,
                ..
            } = m
            {
                if Self::is_builtin_empty_method(&class_def.name, name, body) {
                    continue;
                }
                let ret = self.method_return_type(name, return_type);
                let self_type = Self::c_self_type(&class_def.name);
                out.push_str(&format!(
                    "{} {}_{}({}* self",
                    ret, class_def.name, name, self_type
                ));
                for param in params {
                    let c_type = param
                        .param_type
                        .as_ref()
                        .map(|pt| self.c_type_for(pt))
                        .unwrap_or_else(|| {
                            if let Some(field_ty) = class_def.members.iter().find_map(|m| match m {
                                Member::Field { name, field_type, .. } if name == &param.name => Some(field_type),
                                _ => None,
                            }) {
                                self.c_type_for(field_ty)
                            } else {
                                "void*".to_string()
                            }
                        });
                    out.push_str(&format!(", {} {}", c_type, Self::c_ident(&param.name)));
                }
                out.push_str(");\n");
            }
        }
        Ok(out)
    }

    fn generate_class_impl(&mut self, class_def: &ClassDef) -> Result<String, String> {
        let mut out = String::new();
        self.current_class_name = class_def.name.clone();
        self.current_class_fields.clear();
        self.field_types.clear();

        let mut seen_fields = HashSet::new();
        let mut fields = Vec::new();
        self.collect_all_impl_fields(class_def, &mut seen_fields, &mut fields);

        let is_builtin = Self::is_builtin_runtime_class(&class_def.name);
        if !is_builtin {
            // Constructor
            out.push_str(&format!(
                "{}* {}_new(void) {{\n",
                class_def.name, class_def.name
            ));
            out.push_str(&format!(
                "    {}* self = ({}*)malloc(sizeof({}));\n",
                class_def.name, class_def.name, class_def.name
            ));
            for (field_name, field_type, init_expr) in &fields {
                if let Some(expr) = init_expr {
                    let init_c = self.generate_expression(expr)?;
                    out.push_str(&format!("    self->{} = {};\n", field_name, init_c));
                } else {
                    let default_init = match field_type {
                        Type::Simple(n) if n == "Int" || n == "int" => "0",
                        Type::Simple(n) if n == "Float" || n == "float" => "0.0",
                        Type::Simple(n) if n == "Boolean" || n == "bool" => "false",
                        _ => "NULL",
                    };
                    out.push_str(&format!("    self->{} = {};\n", field_name, default_init));
                }
            }
            out.push_str("    return self;\n");
            out.push_str("}\n\n");

            // Methods
            let has_init = class_def.members.iter().any(|m| match m {
                Member::Method { name, .. } => name == "init",
                _ => false,
            });
            if !has_init {
                out.push_str(&format!(
                    "void {}_init({}* self) {{\n    /* default initializer */\n}}\n\n",
                    class_def.name, class_def.name
                ));
            }
        }

        for m in &class_def.members {
            if let Member::Method {
                name,
                params,
                body,
                return_type,
                ..
            } = m
            {
                if Self::is_builtin_empty_method(&class_def.name, name, body) {
                    continue;
                }
                out.push_str(&self.generate_method(
                    &class_def.name,
                    name,
                    params,
                    body,
                    return_type,
                )?);
            }
        }

        Ok(out)
    }

    fn generate_method(
        &mut self,
        class_name: &str,
        method_name: &str,
        params: &[Parameter],
        body: &[Statement],
        return_type: &Option<Type>,
    ) -> Result<String, String> {
        let mut out = String::new();
        self.local_var_types.clear();

        let self_type = Self::c_self_type(class_name);
        let ret = self.method_return_type(method_name, return_type);
        out.push_str(&format!(
            "{} {}_{}({}* self",
            ret, class_name, method_name, self_type
        ));

        for param in params {
            let (c_type, t) = if let Some(pt) = &param.param_type {
                (self.c_type_for(pt), pt.clone())
            } else if let Some(ft) = self.field_types.get(&param.name) {
                (self.c_type_for(ft), ft.clone())
            } else {
                ("void*".to_string(), Type::Simple("void*".to_string()))
            };
            self.local_var_types.insert(param.name.clone(), t);
            out.push_str(&format!(", {} {}", c_type, Self::c_ident(&param.name)));
        }
        out.push_str(") {\n");

        for param in params {
            if param.is_field_init {
                out.push_str(&format!(
                    "    self->{} = {};\n",
                    Self::c_ident(&param.name),
                    Self::c_ident(&param.name)
                ));
            }
        }

        for stmt in body {
            out.push_str(&self.generate_statement(stmt)?);
        }

        out.push_str("}\n\n");
        Ok(out)
    }

    fn generate_statement(&mut self, stmt: &Statement) -> Result<String, String> {
        let mut out = String::new();
        match stmt {
            Statement::VariableDecl {
                var_type,
                name,
                init,
                ..
            } => {
                self.local_var_types.insert(name.clone(), var_type.clone());
                let c_type = self.c_type_for(var_type);
                if let Some(init_expr) = init {
                    let init_c = self.generate_expression(init_expr)?;
                    out.push_str(&format!("    {} {} = {};\n", c_type, Self::c_ident(name), init_c));
                } else {
                    let default_init = match var_type {
                        Type::Simple(n) if n == "Int" || n == "int" => "0",
                        Type::Simple(n) if n == "Float" || n == "float" => "0.0",
                        Type::Simple(n) if n == "Boolean" || n == "bool" => "false",
                        Type::Simple(n) if self.all_enums.contains_key(n) => "0",
                        _ => "NULL",
                    };
                    out.push_str(&format!("    {} {} = {};\n", c_type, Self::c_ident(name), default_init));
                }
            }
            Statement::Assignment { target, value } => {
                let val_c = self.generate_expression(value)?;
                match target {
                    Expression::Identifier(id) => {
                        if self.current_class_fields.contains(id) {
                            out.push_str(&format!("    self->{} = {};\n", id, val_c));
                        } else {
                            out.push_str(&format!("    {} = {};\n", Self::c_ident(id), val_c));
                        }
                    }
                    Expression::Path(segments) => {
                        let path_c = self.generate_path(segments);
                        out.push_str(&format!("    {} = {};\n", path_c, val_c));
                    }
                    _ => {
                        let target_c = self.generate_expression(target)?;
                        out.push_str(&format!("    {} = {};\n", target_c, val_c));
                    }
                }
            }
            Statement::If {
                condition,
                then_branch,
                else_branch,
            } => {
                let cond_c = self.generate_expression(condition)?;
                out.push_str(&format!("    if ({}) {{\n", cond_c));
                for s in then_branch {
                    out.push_str(&self.generate_statement(s)?);
                }
                if let Some(else_stmts) = else_branch {
                    out.push_str("    } else {\n");
                    for s in else_stmts {
                        out.push_str(&self.generate_statement(s)?);
                    }
                }
                out.push_str("    }\n");
            }
            Statement::When { subject, arms } => {
                let opt_enum = self.infer_target_enum(subject);
                if let Some(ref edef) = opt_enum {
                    let has_else = arms.iter().any(|a| a.is_else);
                    if !has_else {
                        let covered_variants: HashSet<String> = arms
                            .iter()
                            .flat_map(|a| {
                                a.conditions.iter().filter_map(|c| match c {
                                    Expression::Identifier(id) => Some(id.clone()),
                                    Expression::Path(segs) if segs.len() == 2 => Some(segs[1].clone()),
                                    _ => None,
                                })
                            })
                            .collect();
                        let missing: Vec<&str> = edef
                            .variants
                            .iter()
                            .filter(|v| !covered_variants.contains(&v.name))
                            .map(|v| v.name.as_str())
                            .collect();
                        if !missing.is_empty() {
                            return Err(format!(
                                "Non-exhaustive 'when' on Enum '{}'. Missing variant(s): {}. Provide explicit branches or an 'else:' fallback.",
                                edef.name,
                                missing.join(", ")
                            ));
                        }
                    }
                }

                let is_str = self.is_string_expr(subject)
                    || arms
                        .iter()
                        .any(|a| a.conditions.iter().any(|c| matches!(c, Expression::StringLiteral(_))));
                let subj_c = self.generate_expression(subject)?;

                if !is_str {
                    out.push_str(&format!("    switch ({}) {{\n", subj_c));
                    for arm in arms {
                        if arm.is_else {
                            out.push_str("    default: {\n");
                        } else {
                            for cond in &arm.conditions {
                                let cond_c = self.resolve_enum_cond(cond, opt_enum.as_ref())?;
                                out.push_str(&format!("    case {}:\n", cond_c));
                            }
                            out.push_str("    {\n");
                        }
                        for stmt in &arm.body {
                            out.push_str(&self.generate_statement(stmt)?);
                        }
                        out.push_str("        break;\n    }\n");
                    }
                    out.push_str("    }\n");
                } else {
                    let mut first = true;
                    for arm in arms {
                        if arm.is_else {
                            out.push_str(" else {\n");
                        } else {
                            let mut cond_exprs = Vec::new();
                            for c in &arm.conditions {
                                let c_val = self.generate_expression(c)?;
                                cond_exprs.push(format!("(strcmp({}, {}) == 0)", subj_c, c_val));
                            }
                            let joined = cond_exprs.join(" || ");
                            if first {
                                out.push_str(&format!("    if ({}) {{\n", joined));
                                first = false;
                            } else {
                                out.push_str(&format!(" else if ({}) {{\n", joined));
                            }
                        }
                        for stmt in &arm.body {
                            out.push_str(&self.generate_statement(stmt)?);
                        }
                        out.push_str("    }");
                    }
                    out.push_str("\n");
                }
            }
            Statement::Return(opt_expr) => {
                if let Some(expr) = opt_expr {
                    let val_c = self.generate_expression(expr)?;
                    out.push_str(&format!("    return {};\n", val_c));
                } else {
                    out.push_str("    return;\n");
                }
            }
            Statement::Class(_) => {
                // Nested classes are collected upfront into flattened_classes
            }
            Statement::Enum(_) => {
                // Enums are collected upfront and emitted
            }
            Statement::Expression(expr) => {
                let expr_c = self.generate_expression(expr)?;
                out.push_str(&format!("    {};\n", expr_c));
            }
        }
        Ok(out)
    }

    fn generate_path(&self, segments: &[String]) -> String {
        if segments.is_empty() {
            return String::new();
        }
        if segments.len() == 2 && self.all_enums.contains_key(&segments[0]) {
            return format!("{}_{}", segments[0], segments[1]);
        }
        let first = if segments[0] == "self" {
            "self".to_string()
        } else if self.current_class_fields.contains(&segments[0]) {
            format!("self->{}", segments[0])
        } else {
            segments[0].clone()
        };

        if segments.len() == 1 {
            first
        } else {
            let mut s = first;
            for seg in &segments[1..] {
                s = format!("{}->{}", s, seg);
            }
            s
        }
    }

    fn wrap_to_string(&self, expr: &Expression, expr_c: String) -> String {
        match expr {
            Expression::NumberLiteral(_) => format!("spec_to_string_int({})", expr_c),
            Expression::FloatLiteral(_) => format!("spec_to_string_float({})", expr_c),
            Expression::BooleanLiteral(_) => format!("spec_to_string_bool({})", expr_c),
            Expression::Identifier(id) => {
                let t = self
                    .local_var_types
                    .get(id)
                    .or_else(|| self.field_types.get(id));
                if let Some(Type::Simple(name)) = t {
                    match name.as_str() {
                        "Int" | "int" => return format!("spec_to_string_int({})", expr_c),
                        "Float" | "float" => return format!("spec_to_string_float({})", expr_c),
                        "Boolean" | "bool" => return format!("spec_to_string_bool({})", expr_c),
                        _ => {}
                    }
                }
                expr_c
            }
            Expression::Binary { op, .. } if *op != BinaryOp::Concat => {
                format!("spec_to_string_float((double)({}))", expr_c)
            }
            Expression::Unary { .. } => format!("spec_to_string_float((double)({}))", expr_c),
            Expression::MethodCall { method, target, .. } => {
                if let Expression::Identifier(t) = target.as_ref() {
                    if t == "math" {
                        return format!("spec_to_string_float({})", expr_c);
                    }
                }
                if method == "length" || method == "size" {
                    return format!("spec_to_string_int({})", expr_c);
                }
                if method == "isEmpty" {
                    return format!("spec_to_string_bool({})", expr_c);
                }
                if method == "has" || method == "remove" || method == "any" || method == "startsWith" {
                    return format!("spec_to_string_bool({})", expr_c);
                }
                if method == "pop" || method == "removeAt" {
                    let elem_type = self.infer_array_element_type(target);
                    if elem_type == "Int" {
                        return format!("spec_to_string_int({})", expr_c);
                    } else if elem_type == "Float" {
                        return format!("spec_to_string_float({})", expr_c);
                    } else if elem_type == "Boolean" {
                        return format!("spec_to_string_bool({})", expr_c);
                    }
                }
                if method == "indexOf" || method == "execute" || method == "count" || method == "countLeading" || method == "ordinal" {
                    return format!("spec_to_string_int({})", expr_c);
                }
                if method == "value" {
                    if let Some(edef) = self.infer_target_enum(target) {
                        if !matches!(&edef.backing_type, Some(Type::Simple(s)) if s == "String") {
                            return format!("spec_to_string_int({})", expr_c);
                        }
                    } else {
                        return format!("spec_to_string_int({})", expr_c);
                    }
                }
                if method == "isDigit"
                    || method == "isAlpha"
                    || method == "isWhitespace"
                    || method == "exists"
                    || method == "write"
                {
                    return format!("spec_to_string_bool({})", expr_c);
                }
                if method == "abs" || method == "min" || method == "max" || method == "clamp" {
                    return format!("spec_to_string_float({})", expr_c);
                }
                if method == "handValue" || method == "drawCard" {
                    return format!("spec_to_string_int({})", expr_c);
                }
                if let Some(cname) = self.infer_target_class(target) {
                    if let Some(cdef) = self.all_classes.get(&cname) {
                        for m in &cdef.members {
                            if let Member::Method { name, return_type, .. } = m {
                                if name == method {
                                    let ret_c = self.method_return_type(name, return_type);
                                    if ret_c == "long long" {
                                        return format!("spec_to_string_int({})", expr_c);
                                    } else if ret_c == "double" {
                                        return format!("spec_to_string_float({})", expr_c);
                                    } else if ret_c == "bool" {
                                        return format!("spec_to_string_bool({})", expr_c);
                                    }
                                }
                            }
                        }
                    }
                }
                expr_c
            }
            Expression::Path(segments) => {
                if let Some(last) = segments.last() {
                    let mut t = self
                        .local_var_types
                        .get(last)
                        .or_else(|| self.field_types.get(last));

                    if t.is_none() && segments.len() >= 2 {
                        let root_id = &segments[0];
                        let root_type = self
                            .local_var_types
                            .get(root_id)
                            .or_else(|| self.field_types.get(root_id));
                        if let Some(Type::Simple(cname)) = root_type {
                            if let Some(cdef) = self.all_classes.get(cname) {
                                for m in &cdef.members {
                                    if let Member::Field { name, field_type, .. } = m {
                                        if name == last {
                                            t = Some(field_type);
                                            break;
                                        }
                                    }
                                }
                            }
                        }
                    }

                    if let Some(Type::Simple(name)) = t {
                        match name.as_str() {
                            "Int" | "int" => return format!("spec_to_string_int({})", expr_c),
                            "Float" | "float" => return format!("spec_to_string_float({})", expr_c),
                            "Boolean" | "bool" => return format!("spec_to_string_bool({})", expr_c),
                            _ => {}
                        }
                    }
                }
                expr_c
            }
            Expression::Index { target, .. } => {
                let elem_type = self.infer_array_element_type(target);
                if elem_type == "String" {
                    expr_c
                } else {
                    format!("spec_to_string_int({})", expr_c)
                }
            }
            Expression::IfElse { then_expr, .. } => {
                self.wrap_to_string(then_expr, expr_c)
            }
            Expression::When { arms, .. } => {
                if let Some(first) = arms.iter().find_map(|a| a.expr.as_ref()) {
                    self.wrap_to_string(first, expr_c)
                } else {
                    expr_c
                }
            }
            _ => expr_c,
        }
    }

    fn generate_expression(&mut self, expr: &Expression) -> Result<String, String> {
        match expr {
            Expression::StringLiteral(s) => {
                let mut escaped = String::new();
                for ch in s.chars() {
                    match ch {
                        '\n' => escaped.push_str("\\n"),
                        '\t' => escaped.push_str("\\t"),
                        '\r' => escaped.push_str("\\r"),
                        '\"' => escaped.push_str("\\\""),
                        '\\' => escaped.push_str("\\\\"),
                        c => escaped.push(c),
                    }
                }
                Ok(format!("\"{}\"", escaped))
            }
            Expression::NumberLiteral(n) => Ok(format!("{}", n)),
            Expression::FloatLiteral(f) => {
                let mut s = format!("{}", f);
                if !s.contains('.') && !s.contains('e') && !s.contains('E') {
                    s.push_str(".0");
                }
                Ok(s)
            }
            Expression::BooleanLiteral(b) => Ok(if *b { "true" } else { "false" }.to_string()),
            Expression::Identifier(id) => {
                if id == "self" {
                    Ok("self".to_string())
                } else if self.local_var_types.contains_key(id) {
                    Ok(Self::c_ident(id))
                } else if self.current_class_fields.contains(id) {
                    Ok(format!("self->{}", id))
                } else {
                    Ok(id.clone())
                }
            }
            Expression::Unary { op, expr } => match op {
                UnaryOp::Neg => {
                    let sub_c = self.generate_expression(expr)?;
                    Ok(format!("(-{})", sub_c))
                }
                UnaryOp::Not => {
                    let sub_c = self.generate_expression(expr)?;
                    Ok(format!("(!{})", sub_c))
                }
            },
            Expression::Binary { op, left, right } => match op {
                BinaryOp::Concat => {
                    let left_raw = self.generate_expression(left)?;
                    let right_raw = self.generate_expression(right)?;
                    let left_c = self.wrap_to_string(left, left_raw);
                    let right_c = self.wrap_to_string(right, right_raw);
                    Ok(format!("spec_str_concat({}, {})", left_c, right_c))
                }
                BinaryOp::Add => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    Ok(format!("({} + {})", left_c, right_c))
                }
                BinaryOp::Sub => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    Ok(format!("({} - {})", left_c, right_c))
                }
                BinaryOp::Mul => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    Ok(format!("({} * {})", left_c, right_c))
                }
                BinaryOp::Div => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    Ok(format!("({} / {})", left_c, right_c))
                }
                BinaryOp::Mod => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    Ok(format!(
                        "((long long)({}) % (long long)({}))",
                        left_c, right_c
                    ))
                }
                BinaryOp::Equal => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    if self.is_string_expr(left) || self.is_string_expr(right) {
                        Ok(format!("(strcmp({}, {}) == 0)", left_c, right_c))
                    } else {
                        Ok(format!("({} == {})", left_c, right_c))
                    }
                }
                BinaryOp::NotEqual => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    if self.is_string_expr(left) || self.is_string_expr(right) {
                        Ok(format!("(strcmp({}, {}) != 0)", left_c, right_c))
                    } else {
                        Ok(format!("({} != {})", left_c, right_c))
                    }
                }
                BinaryOp::Less => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    Ok(format!("({} < {})", left_c, right_c))
                }
                BinaryOp::LessEqual => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    Ok(format!("({} <= {})", left_c, right_c))
                }
                BinaryOp::Greater => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    Ok(format!("({} > {})", left_c, right_c))
                }
                BinaryOp::GreaterEqual => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    Ok(format!("({} >= {})", left_c, right_c))
                }
                BinaryOp::And => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    Ok(format!("({} && {})", left_c, right_c))
                }
                BinaryOp::Or => {
                    let left_c = self.generate_expression(left)?;
                    let right_c = self.generate_expression(right)?;
                    Ok(format!("({} || {})", left_c, right_c))
                }
            },
            Expression::Index { target, index } => {
                let target_c = self.generate_expression(target)?;
                let index_c = self.generate_expression(index)?;
                let elem_type = self.infer_array_element_type(target);
                if elem_type == "String" {
                    Ok(format!(
                        "((const char*)spec_array_get({}, (size_t)({})))",
                        target_c, index_c
                    ))
                } else {
                    Ok(format!(
                        "((long long)(intptr_t)spec_array_get({}, (size_t)({})))",
                        target_c, index_c
                    ))
                }
            }
            Expression::MethodCall {
                target,
                method,
                args,
            } => {
                // Check if target is a Class identifier calling `:init(...)`
                if let Expression::Identifier(target_name) = target.as_ref() {
                    if self.all_enums.contains_key(target_name) && method == "values" {
                        return Ok(format!("{}_values()", target_name));
                    }
                    if method == "init" {
                        if target_name == "Map" {
                            return Ok("spec_map_new()".to_string());
                        }
                        if target_name == "Array" {
                            return Ok("spec_array_new()".to_string());
                        }
                        if target_name == "LoopControl" {
                            if args.is_empty() {
                                return Ok("LoopControl_new()".to_string());
                            } else {
                                let cb_c = self.generate_expression(&args[0].value)?;
                                return Ok(format!(
                                    "({{ SpecLoopControl* _c = LoopControl_new(); _c->callback = (void*)({}); _c->on_complete = (void (*)(void*, struct SpecLoopControl*))DealerTurnCompleteCallback_onComplete; _c; }})",
                                    cb_c
                                ));
                            }
                        }

                        // General <Class>:init(...) instantiation
                        let mut arg_c_list = Vec::new();
                        for arg in args {
                            arg_c_list.push(self.generate_expression(&arg.value)?);
                        }
                        let joined_args = if arg_c_list.is_empty() {
                            String::new()
                        } else {
                            format!(", {}", arg_c_list.join(", "))
                        };
                        return Ok(format!(
                            "({{ {}* _inst = {}_new(); {}_{}(_inst{}); _inst; }})",
                            target_name, target_name, target_name, method, joined_args
                        ));
                    }

                    // Check for While:run(loop, control)
                    if target_name == "While" && method == "run" {
                        let loop_c = self.generate_expression(&args[0].value)?;
                        let ctrl_c = if args.len() > 1 {
                            self.generate_expression(&args[1].value)?
                        } else {
                            "NULL".to_string()
                        };

                        // Determine the class name of the loop
                        let loop_class = self.infer_loop_class(&args[0].value);
                        return Ok(format!(
                            "({{ void* _lp = (void*)({}); SpecLoopControl* _ctrl = (SpecLoopControl*)({}); while ({}_evaluate((void*)_lp)) {{ if (!{}_iteration((void*)_lp, _ctrl) || (_ctrl && _ctrl->stopped)) {{ break; }} }} if (_ctrl && _ctrl->on_complete) {{ _ctrl->on_complete(_ctrl->callback, _ctrl); }} }})",
                            loop_c, ctrl_c, loop_class, loop_class
                        ));
                    }

                    // Check for Input:prompt(handler)
                    if target_name == "Input" && method == "prompt" {
                        let handler_c = self.generate_expression(&args[0].value)?;
                        return Ok(format!(
                            "({{ char _buf[256]; char* _res = \"s\"; if (fgets(_buf, sizeof(_buf), stdin)) {{ size_t _len = strlen(_buf); if (_len > 0 && _buf[_len - 1] == '\\n') _buf[_len - 1] = '\\0'; _res = strdup(_buf); }} PlayerTurnHandler_onInput((void*)({}), _res); }})",
                            handler_c
                        ));
                    }

                    // Check for output:line(...)
                    if target_name == "output" && method == "line" {
                        let arg_c = if let Some(first_arg) = args.first() {
                            let raw_c = self.generate_expression(&first_arg.value)?;
                            self.wrap_to_string(&first_arg.value, raw_c)
                        } else {
                            "\"\"".to_string()
                        };
                        return Ok(format!("spec_output_line({})", arg_c));
                    }

                    // Check for math package calls
                    if target_name == "math" {
                        match method.as_str() {
                            "round" => {
                                let val = self.extract_arg(args, "value", 0)?;
                                return Ok(format!("spec_math_round({})", val));
                            }
                            "floor" => {
                                let val = self.extract_arg(args, "value", 0)?;
                                return Ok(format!("((long long)spec_math_floor({}))", val));
                            }
                            "ceil" | "ceiling" => {
                                let val = self.extract_arg(args, "value", 0)?;
                                return Ok(format!("((long long)spec_math_ceil({}))", val));
                            }
                            "random" => {
                                if args.is_empty() {
                                    return Ok("spec_math_random_default()".to_string());
                                } else {
                                    let min_val = self.extract_arg(args, "min", 0)?;
                                    let max_val = self.extract_arg(args, "max", 1)?;
                                    return Ok(format!(
                                        "spec_math_random({}, {})",
                                        min_val, max_val
                                    ));
                                }
                            }
                            _ => {}
                        }
                    }
                }

                if let Expression::Identifier(target_name) = target.as_ref() {
                    if target_name == "File" {
                        match method.as_str() {
                            "read" => {
                                let path_c = self.extract_arg_named(args, "path", 0)?;
                                let def_c = self.extract_arg_opt(args, "default")?.unwrap_or_else(|| "\"\"".to_string());
                                let on_succ = self.extract_arg_opt(args, "onSuccess")?.unwrap_or_else(|| "NULL".to_string());
                                let on_err = self.extract_arg_opt(args, "onError")?.unwrap_or_else(|| "NULL".to_string());
                                return Ok(format!(
                                    "spec_file_read({}, {}, (void (*)(const char*))({}), (void (*)(const char*))({}))",
                                    path_c, def_c, on_succ, on_err
                                ));
                            }
                            "readAsync" => {
                                let path_c = self.extract_arg_named(args, "path", 0)?;
                                let def_c = self.extract_arg_opt(args, "default")?.unwrap_or_else(|| "\"\"".to_string());
                                let on_succ = self.extract_arg_opt(args, "onSuccess")?.unwrap_or_else(|| "NULL".to_string());
                                let on_err = self.extract_arg_opt(args, "onError")?.unwrap_or_else(|| "NULL".to_string());
                                return Ok(format!(
                                    "spec_file_read_async({}, {}, (void (*)(const char*))({}), (void (*)(const char*))({}))",
                                    path_c, def_c, on_succ, on_err
                                ));
                            }
                            "write" => {
                                let path_c = self.extract_arg_named(args, "path", 0)?;
                                let content_c = self.extract_arg_named(args, "content", 1)?;
                                let on_succ = self.extract_arg_opt(args, "onSuccess")?.unwrap_or_else(|| "NULL".to_string());
                                let on_err = self.extract_arg_opt(args, "onError")?.unwrap_or_else(|| "NULL".to_string());
                                return Ok(format!(
                                    "spec_file_write({}, {}, (void (*)(long long))({}), (void (*)(const char*))({}))",
                                    path_c, content_c, on_succ, on_err
                                ));
                            }
                            "writeAsync" => {
                                let path_c = self.extract_arg_named(args, "path", 0)?;
                                let content_c = self.extract_arg_named(args, "content", 1)?;
                                let on_succ = self.extract_arg_opt(args, "onSuccess")?.unwrap_or_else(|| "NULL".to_string());
                                let on_err = self.extract_arg_opt(args, "onError")?.unwrap_or_else(|| "NULL".to_string());
                                return Ok(format!(
                                    "spec_file_write_async({}, {}, (void (*)(long long))({}), (void (*)(const char*))({}))",
                                    path_c, content_c, on_succ, on_err
                                ));
                            }
                            "exists" => {
                                let path_c = self.extract_arg(args, "path", 0)?;
                                return Ok(format!("spec_file_exists({})", path_c));
                            }
                            _ => {}
                        }
                    }

                    if target_name == "Process" {
                        if method == "execute" {
                            let cmd_c = self.extract_arg(args, "command", 0)?;
                            let args_c = self.extract_arg(args, "args", 1)?;
                            return Ok(format!("spec_process_execute({}, {})", cmd_c, args_c));
                        }
                    }

                    // Named constructor or method on class: <Class>:<method>(...)
                    if self.all_classes.contains_key(target_name) {
                        let mut arg_c_list = Vec::new();
                        for arg in args {
                            arg_c_list.push(self.generate_expression(&arg.value)?);
                        }
                        let joined_args = if arg_c_list.is_empty() {
                            String::new()
                        } else {
                            format!(", {}", arg_c_list.join(", "))
                        };
                        return Ok(format!(
                            "({{ {}* _inst = {}_new(); {}_{}(_inst{}); _inst; }})",
                            target_name, target_name, target_name, method, joined_args
                        ));
                    }
                }

                // Check for String inspection methods
                if method == "charAt" {
                    let target_c = self.generate_expression(target)?;
                    let idx_c = self.extract_arg(args, "index", 0)?;
                    let def_c = self.extract_arg(args, "default", 1)?;
                    return Ok(format!("spec_str_char_at({}, {}, {})", target_c, idx_c, def_c));
                }

                if method == "substring" {
                    let target_c = self.generate_expression(target)?;
                    let start_c = self.extract_arg(args, "start", 0)?;
                    let end_c = self.extract_arg(args, "end", 1)?;
                    return Ok(format!("spec_str_substring({}, {}, {})", target_c, start_c, end_c));
                }

                if method == "indexOf" {
                    let target_c = self.generate_expression(target)?;
                    let needle_c = self.extract_arg(args, "search", 0)?;
                    let def_c = self.extract_arg(args, "default", 1)?;
                    let is_arr = if let Expression::Identifier(ref id) = **target {
                        matches!(
                            self.local_var_types.get(id).or_else(|| self.field_types.get(id)),
                            Some(Type::Simple(n)) if n == "Array" || n == "array"
                        ) || matches!(
                            self.local_var_types.get(id).or_else(|| self.field_types.get(id)),
                            Some(Type::Generic(n, _)) if n == "Array" || n == "array"
                        )
                    } else {
                        false
                    };
                    if is_arr {
                        return Ok(format!("spec_array_index_of_str({}, {}, {})", target_c, needle_c, def_c));
                    } else {
                        return Ok(format!("spec_str_index_of({}, {}, {})", target_c, needle_c, def_c));
                    }
                }

                if method == "isDigit" {
                    let target_c = self.generate_expression(target)?;
                    return Ok(format!("spec_str_is_digit({})", target_c));
                }

                if method == "isAlpha" {
                    let target_c = self.generate_expression(target)?;
                    return Ok(format!("spec_str_is_alpha({})", target_c));
                }

                if method == "isWhitespace" {
                    let target_c = self.generate_expression(target)?;
                    return Ok(format!("spec_str_is_whitespace({})", target_c));
                }

                // String helper inspection methods
                if method == "lines" {
                    let target_c = self.generate_expression(target)?;
                    return Ok(format!("spec_str_lines({})", target_c));
                }

                if method == "startsWith" {
                    let target_c = self.generate_expression(target)?;
                    let prefix_c = self.extract_arg(args, "prefix", 0)?;
                    return Ok(format!("spec_str_starts_with({}, {})", target_c, prefix_c));
                }

                if method == "countLeading" {
                    let target_c = self.generate_expression(target)?;
                    let search_c = self.extract_arg(args, "search", 0)?;
                    return Ok(format!("spec_str_count_leading({}, {})", target_c, search_c));
                }

                if method == "trim" {
                    let target_c = self.generate_expression(target)?;
                    return Ok(format!("spec_str_trim({})", target_c));
                }

                // Array higher-order methods
                if method == "each" {
                    let target_c = self.generate_expression(target)?;
                    let fn_c = self.extract_arg(args, "action", 0)?;
                    return Ok(format!("spec_array_each({}, (void (*)(void*))({}))", target_c, fn_c));
                }

                if method == "any" {
                    let target_c = self.generate_expression(target)?;
                    let fn_c = self.extract_arg(args, "predicate", 0)?;
                    return Ok(format!("spec_array_any({}, (bool (*)(void*))({}))", target_c, fn_c));
                }

                if method == "count" {
                    let target_c = self.generate_expression(target)?;
                    let fn_c = self.extract_arg(args, "predicate", 0)?;
                    return Ok(format!("spec_array_count({}, (bool (*)(void*))({}))", target_c, fn_c));
                }

                if method == "filter" {
                    let target_c = self.generate_expression(target)?;
                    let fn_c = self.extract_arg(args, "predicate", 0)?;
                    return Ok(format!("spec_array_filter({}, (bool (*)(void*))({}))", target_c, fn_c));
                }

                // Check for `control:stop()`
                if method == "stop" {
                    let target_c = self.generate_expression(target)?;
                    return Ok(format!("LoopControl_stop({})", target_c));
                }

                // Check for `args:getString(key: '...', default: '...')`
                if method == "getString" {
                    let target_c = self.generate_expression(target)?;
                    let mut key_val = "\"\"".to_string();
                    let mut def_val = "\"\"".to_string();

                    for arg in args {
                        if let Some(ref name) = arg.name {
                            if name == "key" {
                                key_val = self.generate_expression(&arg.value)?;
                            } else if name == "default" {
                                def_val = self.generate_expression(&arg.value)?;
                            }
                        }
                    }
                    return Ok(format!(
                        "spec_map_get_string({}, {}, {})",
                        target_c, key_val, def_val
                    ));
                }

                // Check for length / size (Map, String, or Array)
                if method == "length" || method == "size" {
                    let target_c = self.generate_expression(target)?;
                    let is_map = if let Expression::Identifier(ref id) = **target {
                        matches!(
                            self.local_var_types.get(id).or_else(|| self.field_types.get(id)),
                            Some(Type::Simple(n)) if n == "Map" || n == "map"
                        ) || matches!(
                            self.local_var_types.get(id).or_else(|| self.field_types.get(id)),
                            Some(Type::Generic(n, _)) if n == "Map" || n == "map"
                        )
                    } else {
                        false
                    };
                    if is_map {
                        return Ok(format!("spec_map_length({})", target_c));
                    }
                    let is_str = self.is_string_expr(target);
                    if is_str {
                        return Ok(format!("spec_str_length({})", target_c));
                    } else {
                        return Ok(format!("spec_array_length({})", target_c));
                    }
                }

                if method == "set" {
                    let target_c = self.generate_expression(target)?;
                    let key_c = self.extract_arg(args, "key", 0)?;
                    let val_c = self.extract_arg(args, "value", 1)?;
                    return Ok(format!("spec_map_set({}, {}, {})", target_c, key_c, val_c));
                }

                if method == "has" {
                    let target_c = self.generate_expression(target)?;
                    let key_c = self.extract_arg(args, "key", 0)?;
                    return Ok(format!("spec_map_has({}, {})", target_c, key_c));
                }

                if method == "remove" {
                    let target_c = self.generate_expression(target)?;
                    let key_c = self.extract_arg(args, "key", 0)?;
                    return Ok(format!("spec_map_remove({}, {})", target_c, key_c));
                }

                if method == "keys" {
                    let target_c = self.generate_expression(target)?;
                    return Ok(format!("spec_map_keys({})", target_c));
                }

                if method == "pop" {
                    let target_c = self.generate_expression(target)?;
                    let def_c = self.extract_arg(args, "default", 0)?;
                    let elem_type = self.infer_array_element_type(target);
                    if elem_type == "String" {
                        return Ok(format!("((const char*)spec_array_pop({}, (void*)({})))", target_c, def_c));
                    } else {
                        return Ok(format!("((long long)(intptr_t)spec_array_pop({}, (void*)({})))", target_c, def_c));
                    }
                }

                if method == "removeAt" {
                    let target_c = self.generate_expression(target)?;
                    let idx_c = self.extract_arg(args, "index", 0)?;
                    let def_c = self.extract_arg(args, "default", 1)?;
                    let elem_type = self.infer_array_element_type(target);
                    if elem_type == "String" {
                        return Ok(format!("((const char*)spec_array_remove_at({}, (size_t)({}), (void*)({})))", target_c, idx_c, def_c));
                    } else {
                        return Ok(format!("((long long)(intptr_t)spec_array_remove_at({}, (size_t)({}), (void*)({})))", target_c, idx_c, def_c));
                    }
                }

                if method == "slice" {
                    let target_c = self.generate_expression(target)?;
                    let start_c = self.extract_arg(args, "start", 0)?;
                    let end_c = self.extract_arg(args, "end", 1)?;
                    return Ok(format!("spec_array_slice({}, {}, {})", target_c, start_c, end_c));
                }

                if method == "clear" {
                    let target_c = self.generate_expression(target)?;
                    return Ok(format!("spec_array_clear({})", target_c));
                }

                if method == "get" {
                    let target_c = self.generate_expression(target)?;
                    let idx_c = self.extract_arg(args, "index", 0)?;
                    return Ok(format!("spec_array_get({}, (size_t)({}))", target_c, idx_c));
                }

                if method == "add" || method == "push" {
                    let target_c = self.generate_expression(target)?;
                    let is_array_arg = if let Some(first) = args.first() {
                        if let Some(ref n) = first.name {
                            n == "items"
                        } else {
                            matches!(first.value, Expression::ArrayLiteral(_))
                                || if let Expression::Identifier(ref id) = first.value {
                                    let t = self
                                        .local_var_types
                                        .get(id)
                                        .or_else(|| self.field_types.get(id));
                                    matches!(t, Some(Type::Simple(n)) if n == "Array")
                                        || matches!(t, Some(Type::Generic(n, _)) if n == "Array")
                                } else {
                                    false
                                }
                        }
                    } else {
                        false
                    };

                    let item_c = self.extract_arg(
                        args,
                        if is_array_arg { "items" } else { "item" },
                        0,
                    )?;
                    if is_array_arg {
                        return Ok(format!("spec_array_add_array({}, {})", target_c, item_c));
                    } else {
                        return Ok(format!(
                            "spec_array_add({}, (void*)({}))",
                            target_c, item_c
                        ));
                    }
                }

                if let Expression::Identifier(ref id) = **target {
                    if id == "self" {
                        if let Some(t) = self.local_var_types.get(method).or_else(|| self.field_types.get(method)) {
                            if matches!(t, Type::Simple(n) if n == "Function") || matches!(t, Type::Generic(n, _) if n == "Function") {
                                let fn_expr = if self.local_var_types.contains_key(method) {
                                    Self::c_ident(method)
                                } else {
                                    format!("self->{}", method)
                                };
                                let mut arg_c_list = Vec::new();
                                for arg in args {
                                    arg_c_list.push(self.generate_expression(&arg.value)?);
                                }
                                let joined = arg_c_list.join(", ");
                                return Ok(format!("((void* (*)(void*))({}))({})", fn_expr, joined));
                            }
                        }
                    }
                }
                if method.is_empty() {
                    let fn_c = self.generate_expression(target)?;
                    let mut arg_c_list = Vec::new();
                    for arg in args {
                        arg_c_list.push(self.generate_expression(&arg.value)?);
                    }
                    let joined = arg_c_list.join(", ");
                    return Ok(format!("((void* (*)(void*))({}))({})", fn_c, joined));
                }

                // Method call on enum instance
                if let Some(edef) = self.infer_target_enum(target) {
                    let target_c = self.generate_expression(target)?;
                    match method.as_str() {
                        "name" => return Ok(format!("{}_name({})", edef.name, target_c)),
                        "value" => return Ok(format!("{}_value({})", edef.name, target_c)),
                        "ordinal" => return Ok(format!("{}_ordinal({})", edef.name, target_c)),
                        "toString" => {
                            if matches!(&edef.backing_type, Some(Type::Simple(s)) if s == "String") {
                                return Ok(format!("{}_value({})", edef.name, target_c));
                            } else {
                                return Ok(format!("{}_name({})", edef.name, target_c));
                            }
                        }
                        _ => {}
                    }
                }

                // Method call on self or other instance
                let class_name = self.infer_target_class(target);
                let target_c = if let Expression::Identifier(ref id) = **target {
                    if id == "math" {
                        "NULL".to_string()
                    } else {
                        self.generate_expression(target)?
                    }
                } else {
                    self.generate_expression(target)?
                };
                let mut arg_strings = Vec::new();
                for arg in args {
                    arg_strings.push(self.generate_expression(&arg.value)?);
                }
                if let Some(cname) = class_name {
                    let actual_class = self.find_class_for_method(&cname, method).unwrap_or(cname);
                    let joined = if arg_strings.is_empty() {
                        String::new()
                    } else {
                        format!(", {}", arg_strings.join(", "))
                    };
                    Ok(format!("{}_{}({}{})", actual_class, method, target_c, joined))
                } else {
                    let joined = if arg_strings.is_empty() {
                        String::new()
                    } else {
                        format!(", {}", arg_strings.join(", "))
                    };
                    Ok(format!(
                        "{}_{}({}{})",
                        self.current_class_name, method, target_c, joined
                    ))
                }
            }
            Expression::Path(segments) => Ok(self.generate_path(segments)),
            Expression::ArrayLiteral(items) => {
                let mut out = String::from("({ SpecArray* _arr = spec_array_new(); ");
                for item in items {
                    let item_c = self.generate_expression(item)?;
                    out.push_str(&format!("spec_array_add(_arr, (void*)({})); ", item_c));
                }
                out.push_str("_arr; })");
                Ok(out)
            }
            Expression::AnonymousFunction {
                return_type,
                params,
                body,
            } => {
                self.anon_fn_counter += 1;
                let fn_name = format!("_anon_fn_{}", self.anon_fn_counter);
                let old_locals = self.local_var_types.clone();

                let ret_c = if let Some(t) = return_type {
                    self.c_type_for(t)
                } else {
                    fn find_return(stmts: &[Statement]) -> Option<&Expression> {
                        for s in stmts {
                            match s {
                                Statement::Return(Some(e)) => return Some(e),
                                Statement::If {
                                    then_branch,
                                    else_branch,
                                    ..
                                } => {
                                    if let Some(e) = find_return(then_branch) {
                                        return Some(e);
                                    }
                                    if let Some(eb) = else_branch {
                                        if let Some(e) = find_return(eb) {
                                            return Some(e);
                                        }
                                    }
                                }
                                _ => {}
                            }
                        }
                        None
                    }
                    if let Some(ret_expr) = find_return(body) {
                        if self.is_string_expr(ret_expr) {
                            "const char*".to_string()
                        } else if matches!(ret_expr, Expression::Binary { op, .. } if matches!(op, BinaryOp::Equal | BinaryOp::NotEqual | BinaryOp::Less | BinaryOp::LessEqual | BinaryOp::Greater | BinaryOp::GreaterEqual | BinaryOp::And | BinaryOp::Or))
                            || matches!(ret_expr, Expression::MethodCall { method, .. } if matches!(method.as_str(), "startsWith" | "isDigit" | "isAlpha" | "isWhitespace" | "has" | "any"))
                            || matches!(ret_expr, Expression::BooleanLiteral(_))
                        {
                            "bool".to_string()
                        } else if matches!(ret_expr, Expression::NumberLiteral(_)) {
                            "long long".to_string()
                        } else if matches!(ret_expr, Expression::FloatLiteral(_)) {
                            "double".to_string()
                        } else {
                            "void*".to_string()
                        }
                    } else {
                        "void".to_string()
                    }
                };

                let mut param_c_list = Vec::new();
                for p in params {
                    let pt = p
                        .param_type
                        .clone()
                        .unwrap_or(Type::Simple("void*".to_string()));
                    let c_t = p
                        .param_type
                        .as_ref()
                        .map(|t| self.c_type_for(t))
                        .unwrap_or_else(|| "void*".to_string());
                    self.local_var_types.insert(p.name.clone(), pt);
                    param_c_list.push(format!("{} {}", c_t, Self::c_ident(&p.name)));
                }
                let params_c = if param_c_list.is_empty() {
                    "void".to_string()
                } else {
                    param_c_list.join(", ")
                };

                let mut body_c = String::new();
                for stmt in body {
                    body_c.push_str(&self.generate_statement(stmt)?);
                }
                self.local_var_types = old_locals;

                Ok(format!(
                    "({{ {} {}({}) {{\n{} }}; {}; }})",
                    ret_c, fn_name, params_c, body_c, fn_name
                ))
            }
            Expression::IfElse {
                condition,
                then_expr,
                else_expr,
            } => {
                let cond_c = self.generate_expression(condition)?;
                let then_c = self.generate_expression(then_expr)?;
                let else_c = self.generate_expression(else_expr)?;
                Ok(format!("(({}) ? ({}) : ({}))", cond_c, then_c, else_c))
            }
            Expression::When { subject, arms } => {
                let opt_enum = self.infer_target_enum(subject);
                if let Some(ref edef) = opt_enum {
                    let has_else = arms.iter().any(|a| a.is_else);
                    if !has_else {
                        let covered_variants: HashSet<String> = arms
                            .iter()
                            .flat_map(|a| {
                                a.conditions.iter().filter_map(|c| match c {
                                    Expression::Identifier(id) => Some(id.clone()),
                                    Expression::Path(segs) if segs.len() == 2 => Some(segs[1].clone()),
                                    _ => None,
                                })
                            })
                            .collect();
                        let missing: Vec<&str> = edef
                            .variants
                            .iter()
                            .filter(|v| !covered_variants.contains(&v.name))
                            .map(|v| v.name.as_str())
                            .collect();
                        if !missing.is_empty() {
                            return Err(format!(
                                "Non-exhaustive 'when' on Enum '{}'. Missing variant(s): {}. Provide explicit branches or an 'else:' fallback.",
                                edef.name,
                                missing.join(", ")
                            ));
                        }
                    }
                } else {
                    let has_else = arms.iter().any(|a| a.is_else);
                    if !has_else {
                        return Err(
                            "When expression on non-enum type must have an 'else:' fallback branch.".to_string(),
                        );
                    }
                }

                let ret_c = if arms.iter().any(|a| {
                    if let Some(ref e) = a.expr {
                        self.is_string_expr(e)
                    } else if let Some(Statement::Return(Some(e))) | Some(Statement::Expression(e)) = a.body.last() {
                        self.is_string_expr(e)
                    } else {
                        false
                    }
                }) {
                    "const char*"
                } else if arms.iter().any(|a| {
                    let check = |e: &Expression| matches!(e, Expression::BooleanLiteral(_));
                    if let Some(ref e) = a.expr {
                        check(e)
                    } else if let Some(Statement::Return(Some(e))) | Some(Statement::Expression(e)) = a.body.last() {
                        check(e)
                    } else {
                        false
                    }
                }) {
                    "bool"
                } else if arms.iter().any(|a| {
                    let check = |e: &Expression| matches!(e, Expression::FloatLiteral(_));
                    if let Some(ref e) = a.expr {
                        check(e)
                    } else if let Some(Statement::Return(Some(e))) | Some(Statement::Expression(e)) = a.body.last() {
                        check(e)
                    } else {
                        false
                    }
                }) {
                    "double"
                } else if arms.iter().any(|a| {
                    let check = |e: &Expression| matches!(e, Expression::NumberLiteral(_));
                    if let Some(ref e) = a.expr {
                        check(e)
                    } else if let Some(Statement::Return(Some(e))) | Some(Statement::Expression(e)) = a.body.last() {
                        check(e)
                    } else {
                        false
                    }
                }) {
                    "long long"
                } else {
                    let mut arm_enum = None;
                    for a in arms {
                        if let Some(ref e) = a.expr {
                            if let Some(edef) = self.infer_target_enum(e) {
                                arm_enum = Some(edef.name);
                                break;
                            }
                        } else if let Some(Statement::Return(Some(e))) | Some(Statement::Expression(e)) = a.body.last() {
                            if let Some(edef) = self.infer_target_enum(e) {
                                arm_enum = Some(edef.name);
                                break;
                            }
                        }
                    }
                    if let Some(ename) = arm_enum {
                        Box::leak(ename.into_boxed_str()) as &str
                    } else {
                        "void*"
                    }
                };

                let default_val = match ret_c {
                    "const char*" => "\"\"",
                    "bool" => "false",
                    "double" => "0.0",
                    "void*" => "NULL",
                    _ => "0",
                };

                let is_str = self.is_string_expr(subject)
                    || arms
                        .iter()
                        .any(|a| a.conditions.iter().any(|c| matches!(c, Expression::StringLiteral(_))));
                let subj_c = self.generate_expression(subject)?;

                let mut out = String::new();
                out.push_str("({\n");
                out.push_str(&format!("        {} _when_res = {};\n", ret_c, default_val));
                if !is_str {
                    out.push_str(&format!("        switch ({}) {{\n", subj_c));
                    for arm in arms {
                        if arm.is_else {
                            out.push_str("        default: {\n");
                        } else {
                            for cond in &arm.conditions {
                                let cond_c = self.resolve_enum_cond(cond, opt_enum.as_ref())?;
                                out.push_str(&format!("        case {}:\n", cond_c));
                            }
                            out.push_str("        {\n");
                        }
                        if let Some(ref e) = arm.expr {
                            let val_c = self.generate_expression(e)?;
                            out.push_str(&format!("            _when_res = ({});\n", val_c));
                        } else if !arm.body.is_empty() {
                            let len = arm.body.len();
                            for stmt in &arm.body[..len - 1] {
                                out.push_str(&self.generate_statement(stmt)?);
                            }
                            match &arm.body[len - 1] {
                                Statement::Return(Some(e)) | Statement::Expression(e) => {
                                    let val_c = self.generate_expression(e)?;
                                    out.push_str(&format!("            _when_res = ({});\n", val_c));
                                }
                                other => {
                                    out.push_str(&self.generate_statement(other)?);
                                }
                            }
                        }
                        out.push_str("            break;\n        }\n");
                    }
                    out.push_str("        }\n");
                } else {
                    let mut first = true;
                    for arm in arms {
                        if arm.is_else {
                            out.push_str(" else {\n");
                        } else {
                            let mut cond_exprs = Vec::new();
                            for c in &arm.conditions {
                                let c_val = self.generate_expression(c)?;
                                cond_exprs.push(format!("(strcmp({}, {}) == 0)", subj_c, c_val));
                            }
                            let joined = cond_exprs.join(" || ");
                            if first {
                                out.push_str(&format!("        if ({}) {{\n", joined));
                                first = false;
                            } else {
                                out.push_str(&format!(" else if ({}) {{\n", joined));
                            }
                        }
                        if let Some(ref e) = arm.expr {
                            let val_c = self.generate_expression(e)?;
                            out.push_str(&format!("            _when_res = ({});\n", val_c));
                        } else if !arm.body.is_empty() {
                            let len = arm.body.len();
                            for stmt in &arm.body[..len - 1] {
                                out.push_str(&self.generate_statement(stmt)?);
                            }
                            match &arm.body[len - 1] {
                                Statement::Return(Some(e)) | Statement::Expression(e) => {
                                    let val_c = self.generate_expression(e)?;
                                    out.push_str(&format!("            _when_res = ({});\n", val_c));
                                }
                                other => {
                                    out.push_str(&self.generate_statement(other)?);
                                }
                            }
                        }
                        out.push_str("        }");
                    }
                    out.push_str("\n");
                }
                out.push_str("        _when_res;\n    })");
                Ok(out)
            }
        }
    }

    fn is_string_expr(&self, expr: &Expression) -> bool {
        match expr {
            Expression::StringLiteral(_) => true,
            Expression::Identifier(id) => {
                let t = self
                    .local_var_types
                    .get(id)
                    .or_else(|| self.field_types.get(id));
                matches!(t, Some(Type::Simple(name)) if name == "String" || name == "string")
            }
            Expression::Path(segments) => {
                if let Some(last) = segments.last() {
                    let mut t = self
                        .local_var_types
                        .get(last)
                        .or_else(|| self.field_types.get(last));
                    if t.is_none() && segments.len() >= 2 {
                        let root_id = &segments[0];
                        let root_type = self
                            .local_var_types
                            .get(root_id)
                            .or_else(|| self.field_types.get(root_id));
                        if let Some(Type::Simple(cname)) = root_type {
                            if let Some(cdef) = self.all_classes.get(cname) {
                                for m in &cdef.members {
                                    if let Member::Field { name, field_type, .. } = m {
                                        if name == last {
                                            t = Some(field_type);
                                            break;
                                        }
                                    }
                                }
                            }
                        }
                    }
                    matches!(t, Some(Type::Simple(name)) if name == "String" || name == "string")
                } else {
                    false
                }
            }
            Expression::MethodCall { target, method, .. } => {
                if method == "name" {
                    return true;
                }
                if method == "value" {
                    if let Some(edef) = self.infer_target_enum(target) {
                        return matches!(&edef.backing_type, Some(Type::Simple(s)) if s == "String");
                    }
                }
                matches!(
                    method.as_str(),
                    "charAt"
                        | "substring"
                        | "getString"
                        | "toString"
                        | "getName"
                        | "getKind"
                        | "getValue"
                        | "read"
                        | "advance"
                        | "trim"
                )
            }
            Expression::IfElse { then_expr, .. } => self.is_string_expr(then_expr),
            Expression::When { arms, .. } => {
                arms.iter().any(|a| {
                    if let Some(ref e) = a.expr {
                        self.is_string_expr(e)
                    } else if let Some(Statement::Return(Some(e))) | Some(Statement::Expression(e)) = a.body.last() {
                        self.is_string_expr(e)
                    } else {
                        false
                    }
                })
            }
            Expression::Binary {
                op: BinaryOp::Concat,
                ..
            } => true,
            _ => false,
        }
    }

    fn infer_array_element_type(&self, target: &Expression) -> String {
        match target {
            Expression::Identifier(id) => {
                if let Some(Type::Generic(gname, params)) = self
                    .local_var_types
                    .get(id)
                    .or_else(|| self.field_types.get(id))
                {
                    if gname == "Array" {
                        if let Some(Type::Simple(ename)) = params.first() {
                            return ename.clone();
                        }
                    }
                }
                if id == "playerHand" || id == "dealerHand" || id == "deck" || id == "hand" || id == "targetDeck" {
                    return "Int".to_string();
                }
            }
            Expression::Path(segments) => {
                if let Some(last) = segments.last() {
                    if last == "playerHand" || last == "dealerHand" || last == "deck" || last == "hand" || last == "targetDeck" {
                        return "Int".to_string();
                    }
                }
            }
            _ => {}
        }
        "String".to_string()
    }

    fn infer_loop_class(&self, expr: &Expression) -> String {
        match expr {
            Expression::Identifier(id) => {
                if let Some(Type::Simple(tname)) = self
                    .local_var_types
                    .get(id)
                    .or_else(|| self.field_types.get(id))
                {
                    return tname.clone();
                }
                if id.contains("deck") || id.contains("Deck") {
                    return "BuildDeckLoop".to_string();
                }
                if id.contains("dealer") || id.contains("Dealer") {
                    return "DealerTurnLoop".to_string();
                }
                if id.contains("score") || id.contains("Score") {
                    return "ScoreLoop".to_string();
                }
                if id.contains("ace") || id.contains("Ace") {
                    return "AceAdjustLoop".to_string();
                }
                "Loop".to_string()
            }
            Expression::MethodCall { target, .. } => {
                if let Expression::Identifier(tname) = target.as_ref() {
                    return tname.clone();
                }
                "Loop".to_string()
            }
            _ => "Loop".to_string(),
        }
    }

    fn infer_target_enum(&self, expr: &Expression) -> Option<EnumDef> {
        match expr {
            Expression::Identifier(id) => {
                if let Some(edef) = self.all_enums.get(id) {
                    return Some(edef.clone());
                }
                let t = self
                    .local_var_types
                    .get(id)
                    .or_else(|| self.field_types.get(id));
                if let Some(Type::Simple(name)) = t {
                    if let Some(edef) = self.all_enums.get(name) {
                        return Some(edef.clone());
                    }
                }
            }
            Expression::Path(segments) => {
                if segments.len() == 2 && self.all_enums.contains_key(&segments[0]) {
                    return self.all_enums.get(&segments[0]).cloned();
                }
                if let Some(last) = segments.last() {
                    let t = self
                        .local_var_types
                        .get(last)
                        .or_else(|| self.field_types.get(last));
                    if let Some(Type::Simple(name)) = t {
                        if let Some(edef) = self.all_enums.get(name) {
                            return Some(edef.clone());
                        }
                    }
                }
            }
            Expression::IfElse { then_expr, .. } => {
                return self.infer_target_enum(then_expr);
            }
            Expression::When { arms, .. } => {
                for a in arms {
                    if let Some(ref e) = a.expr {
                        if let Some(edef) = self.infer_target_enum(e) {
                            return Some(edef);
                        }
                    } else if let Some(Statement::Return(Some(e))) | Some(Statement::Expression(e)) = a.body.last() {
                        if let Some(edef) = self.infer_target_enum(e) {
                            return Some(edef);
                        }
                    }
                }
            }
            _ => {}
        }
        None
    }

    fn resolve_enum_cond(
        &mut self,
        cond: &Expression,
        opt_enum: Option<&EnumDef>,
    ) -> Result<String, String> {
        match cond {
            Expression::Identifier(id) => {
                if let Some(edef) = opt_enum {
                    if edef.variants.iter().any(|v| &v.name == id) {
                        return Ok(format!("{}_{}", edef.name, id));
                    }
                }
                for edef in self.all_enums.values() {
                    if edef.variants.iter().any(|v| &v.name == id) {
                        return Ok(format!("{}_{}", edef.name, id));
                    }
                }
                self.generate_expression(cond)
            }
            Expression::Path(segs) if segs.len() == 2 && self.all_enums.contains_key(&segs[0]) => {
                Ok(format!("{}_{}", segs[0], segs[1]))
            }
            _ => self.generate_expression(cond),
        }
    }

    fn infer_target_class(&self, expr: &Expression) -> Option<String> {
        match expr {
            Expression::Identifier(id) => {
                if id == "self" {
                    return Some(self.current_class_name.clone());
                }
                if id == "math" {
                    return Some("Math".to_string());
                }
                let t = self
                    .local_var_types
                    .get(id)
                    .or_else(|| self.field_types.get(id));
                if let Some(Type::Simple(name)) = t {
                    return Some(name.clone());
                }
                if let Some(Type::Generic(name, _)) = t {
                    return Some(name.clone());
                }
                if id == "game" {
                    return Some("Blackjack".to_string());
                }
                if self.all_classes.contains_key(id) {
                    return Some(id.clone());
                }
            }
            Expression::Path(segments) => {
                if let Some(last) = segments.last() {
                    let mut t = self
                        .local_var_types
                        .get(last)
                        .or_else(|| self.field_types.get(last));
                    if t.is_none() && segments.len() >= 2 {
                        let root_id = &segments[0];
                        let root_type = self
                            .local_var_types
                            .get(root_id)
                            .or_else(|| self.field_types.get(root_id));
                        if let Some(Type::Simple(cname)) = root_type {
                            if let Some(cdef) = self.all_classes.get(cname) {
                                for m in &cdef.members {
                                    if let Member::Field { name, field_type, .. } = m {
                                        if name == last {
                                            t = Some(field_type);
                                            break;
                                        }
                                    }
                                }
                            }
                        }
                    }
                    if let Some(Type::Simple(name)) = t {
                        return Some(name.clone());
                    }
                    if let Some(Type::Generic(name, _)) = t {
                        return Some(name.clone());
                    }
                    if last == "game" {
                        return Some("Blackjack".to_string());
                    }
                }
            }
            Expression::MethodCall { target, method, .. } => {
                if method == "lines" || method == "filter" || method == "slice" {
                    return Some("Array".to_string());
                }
                if let Some(mut current_class) = self.infer_target_class(target) {
                    while let Some(cdef) = self.all_classes.get(&current_class) {
                        for m in &cdef.members {
                            if let Member::Method {
                                name,
                                return_type,
                                ..
                            } = m
                            {
                                if name == method {
                                    if let Some(ret_t) = return_type {
                                        match ret_t {
                                            Type::Simple(ret_name) => {
                                                return Some(ret_name.clone());
                                            }
                                            Type::Generic(gen_name, params) => {
                                                if gen_name == "Function" {
                                                    if let Some(first) = params.first() {
                                                        match first {
                                                            Type::Simple(n) => {
                                                                return Some(n.clone());
                                                            }
                                                            Type::Generic(n, _) => {
                                                                return Some(n.clone());
                                                            }
                                                        }
                                                    }
                                                } else {
                                                    return Some(gen_name.clone());
                                                }
                                            }
                                        }
                                    }
                                }
                            }
                        }
                        if let Some(ref base) = cdef.base_class {
                            current_class = base.clone();
                        } else {
                            break;
                        }
                    }
                }
            }
            _ => {}
        }
        None
    }

    fn extract_arg(&mut self, args: &[NamedArg], name: &str, pos: usize) -> Result<String, String> {
        for arg in args {
            if let Some(ref n) = arg.name {
                if n == name {
                    return self.generate_expression(&arg.value);
                }
            }
        }
        if pos < args.len() {
            return self.generate_expression(&args[pos].value);
        }
        Ok("0".to_string())
    }

    fn extract_arg_opt(&mut self, args: &[NamedArg], name: &str) -> Result<Option<String>, String> {
        for arg in args {
            if let Some(ref n) = arg.name {
                if n == name {
                    return Ok(Some(self.generate_expression(&arg.value)?));
                }
            }
        }
        Ok(None)
    }

    fn extract_arg_named(&mut self, args: &[NamedArg], name: &str, pos: usize) -> Result<String, String> {
        if let Some(val) = self.extract_arg_opt(args, name)? {
            return Ok(val);
        }
        if pos < args.len() {
            return self.generate_expression(&args[pos].value);
        }
        Ok("0".to_string())
    }

    fn generate_main(&self, entry_class: &str) -> String {
        format!(
            r#"
int main(int argc, char** argv) {{
    srand((unsigned int)time(NULL));
    SpecMap* args = spec_map_new();
    for (int i = 1; i < argc; i++) {{
        if (strncmp(argv[i], "--", 2) == 0) {{
            const char* key = argv[i] + 2;
            const char* val = "true";
            if (i + 1 < argc && argv[i + 1][0] != '-') {{
                val = argv[++i];
            }}
            spec_map_set(args, key, val);
        }} else if (argv[i][0] == '-' && argv[i][1] != '\0') {{
            const char* key = argv[i] + 1;
            const char* val = "true";
            if (i + 1 < argc && argv[i + 1][0] != '-') {{
                val = argv[++i];
            }}
            spec_map_set(args, key, val);
        }}
    }}
    {}* app = {}_new();
    {}_init(app, args);
    return 0;
}}
"#,
            entry_class, entry_class, entry_class
        )
    }
