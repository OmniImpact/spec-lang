    pub fn generate(&mut self, program: &Program) -> Result<String, String> {
        let mut out = String::new();

        out.push_str("/* Generated by Spec Stage 0 Compiler */\n");
        out.push_str("#include <stdio.h>\n");
        out.push_str("#include <stdlib.h>\n");
        out.push_str("#include <string.h>\n");
        out.push_str("#include <stdbool.h>\n");
        out.push_str("#include <stdint.h>\n");
        out.push_str("#include <math.h>\n");
        out.push_str("#include <time.h>\n\n");

        out.push_str(&self.runtime_prelude());

        // 1. Flatten all class definitions (including nested classes in classes and methods)
        let mut flattened_classes = Vec::new();
        for class_def in &program.classes {
            self.collect_classes(class_def, &mut flattened_classes);
        }
        let mut seen = HashSet::new();
        flattened_classes.retain(|c| seen.insert(c.name.clone()));

        for class_def in &flattened_classes {
            self.all_classes
                .insert(class_def.name.clone(), class_def.clone());
        }

        // 2. Forward declare structs
        for class_def in &flattened_classes {
            match class_def.name.as_str() {
                "Array" => out.push_str("typedef struct SpecArray Array;\n"),
                "Map" => out.push_str("typedef struct SpecMap Map;\n"),
                "LoopControl" => out.push_str("typedef struct SpecLoopControl LoopControl;\n"),
                _ => out.push_str(&format!(
                    "typedef struct {} {};\n",
                    class_def.name, class_def.name
                )),
            }
        }
        out.push_str("\n");

        // 3. Emit struct definitions
        for class_def in &flattened_classes {
            if Self::is_builtin_runtime_class(&class_def.name) {
                continue;
            }
            out.push_str(&self.generate_struct_def(class_def)?);
        }

        // 4. Forward declare method signatures
        for class_def in &flattened_classes {
            out.push_str(&self.generate_forward_declarations(class_def)?);
        }
        out.push_str("\n");

        // 5. Emit implementations (constructors and methods)
        for class_def in &flattened_classes {
            out.push_str(&self.generate_class_impl(class_def)?);
        }

        // 6. Emit main entry point if an entry class exists
        if let Some(entry_class) = program.classes.first() {
            out.push_str(&self.generate_main(&entry_class.name));
        }

        Ok(out)
    }

    fn collect_classes(&self, class_def: &ClassDef, acc: &mut Vec<ClassDef>) {
        let mut cleaned_members = Vec::new();
        for m in &class_def.members {
            match m {
                Member::Class(nested) => {
                    self.collect_classes(nested, acc);
                }
                Member::Method { body, .. } => {
                    for stmt in body {
                        if let Statement::Class(method_nested) = stmt {
                            self.collect_classes(method_nested, acc);
                        }
                    }
                    cleaned_members.push(m.clone());
                }
                _ => cleaned_members.push(m.clone()),
            }
        }
        acc.push(ClassDef {
            name: class_def.name.clone(),
            base_class: class_def.base_class.clone(),
            members: cleaned_members,
        });
    }

